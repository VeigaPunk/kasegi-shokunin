#!/usr/bin/env bash
# run-controls.sh — round-46 (attempt 2) freeze-check controls runner.
#
# Seat: R46bExecControls (executor).  Lane: kasegi-shokunin.
#
# WHAT IT DOES
#   Re-derives, from committed bytes only, the before-values the round-46 (attempt 2) freeze
#   declares, and writes a receipt:
#
#     (1) corpus/instruments/r46-f29-gate.py (the frozen v1) replayed on four trees:
#           a. the base export of 04af9bc92229232ea5cce8b32bfe59dd969eb26d
#              -> expect fixed=1/7, H7 the only green limb;
#           b. the freeze tree fe0f56b78b811dbb89bc7f2e17580d11b1b6ebd4
#              -> expect fixed=2/7, H4+H7 green;
#           c. the junk fixture tree       -> expect fixed<7 (limbs quoted);
#           d. the fabricated fixture tree -> expect fixed<7 (limbs quoted);
#         the junk/fabricated trees are built by the committed
#         .ufo/waves/round-46/attempt2/controls/f29-fixture.py from the freeze tree.
#     (2) corpus/instruments/r46-mutbat.py (the frozen v1) replayed at the BASE export,
#         --counter c1 and --counter c2 (the two runs are concurrent): the mutant lines and
#         the summary lines must equal the committed before-value receipt
#         .ufo/waves/round-46/attempt2/controls/mutbat-before.txt.
#     (3) the stub-selftest control: the base tree is copied to scratch, its
#         corpus/instruments/r46-counters-selftest-c1.py is replaced by a stub whose cases all
#         pass (it prints failures=0 unconditionally), and the battery is rerun: it must print
#         every mutant uncaught and exit 1.  A battery that graded markers instead of the
#         selftest's own verdict would still report caught mutants — that is the defect this
#         control catches.
#     (4) `bash /home/vgpnk/Projects/shokunin/scripts/sources-census.sh validate --root
#         /home/vgpnk/Projects/shokunin kasegi` -> expect exit 0 and exactly three W04
#         warnings.  Run before the receipt is closed.
#
# READ-ONLY on the lane: git is used only as `git archive` / `git show` (no mutating
# command); the lane's corpus/ and .ufo/ trees are never written.  All scratch lives under
# $HYAKU_SCRATCH/kasegi-r46/R46bExecControls/ and is removed on exit (trap); the receipt is
# written outside the scratch dir.
#
# USAGE
#   bash run-controls.sh [OUT_RECEIPT]
#     OUT_RECEIPT  defaults to the canonical control path
#                  <lane>/.ufo/waves/round-46/attempt2/controls/freeze-controls.txt
#                  (this seat's own run writes into its draft dir; the L1's freeze-check
#                  replay runs it with no argument to land the canonical receipt).
#
# EXIT: 0 when every declared check passes, 1 otherwise.
set -u

LANE=/home/vgpnk/Projects/shokunin/kasegi-shokunin
BASE=04af9bc92229232ea5cce8b32bfe59dd969eb26d
FREEZE=fe0f56b78b811dbb89bc7f2e17580d11b1b6ebd4
PURE_SRC=/fast/scratch/hyaku/kasegi-r46/L1/pure2
CENSUS=/home/vgpnk/Projects/shokunin/scripts/sources-census.sh
SEAT=R46bExecControls
HYAKU=${HYAKU_SCRATCH:-/fast/scratch/hyaku}
# the scratch dir carries the pid so two concurrent runs of this script can never share it
S=$HYAKU/kasegi-r46/$SEAT.$$
OUT=${1:-$LANE/.ufo/waves/round-46/attempt2/controls/freeze-controls.txt}
RECEIPT=$LANE/.ufo/waves/round-46/attempt2/controls/mutbat-before.txt
FIXTURE_REL=.ufo/waves/round-46/attempt2/controls/f29-fixture.py

rm -rf "$S"
mkdir -p "$S/base" "$S/freeze" "$S/tools" "$S/tmp" "$S/work" "$S/hyaku"
trap 'rm -rf -- "$S"' EXIT
export TMPDIR="$S/tmp"
# an isolated HYAKU_SCRATCH keeps the c2 selftest's own scratch inside this seat's dir
export HYAKU_SCRATCH="$S/hyaku"

FAILED=0
CHECKS=0

# the receipt is written fresh on every run (never appended to), so a re-run cannot leave
# two runs' output interleaved in one file.
: >"$OUT"

# ---------------------------------------------------------------- helpers
say() { printf '%s\n' "$*" >>"$OUT"; }
sayq() { printf '%s\n' "$*"; printf '%s\n' "$*" >>"$OUT"; }
check() {  # check <name> <expected> <actual>
  CHECKS=$((CHECKS + 1))
  if [ "$2" = "$3" ]; then
    say "CHECK $1: PASS (expected=$2 actual=$3)"
  else
    FAILED=$((FAILED + 1))
    say "CHECK $1: FAIL (expected=$2 actual=$3)"
  fi
}
gate_summary() {  # gate_summary <root> -> "<fixed>/7 <green limbs>"
  python3 "$GATE" --root "$1" --work "$S/work/gate-sum-$$-$RANDOM" 2>/dev/null | python3 -c '
import sys
fixed = "?"; green = []
for ln in sys.stdin:
    ln = ln.strip()
    if ln.startswith("gate "):
        p = ln.split()
        if len(p) >= 3 and p[2] == "pass=1":
            green.append(p[1])
    elif ln.startswith("f29-gate fixed="):
        fixed = ln.split()[1].split("=")[1].split("/")[0]
print("%s/7 %s" % (fixed, ",".join(green) if green else "-"))
'
}

say "# round-46 (attempt 2) freeze-check controls receipt"
say "# generated by $SEAT: .ufo/waves/round-46/attempt2/wave1/$SEAT.draft/run-controls.sh"
say "# generated-at: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
say "# lane: $LANE"
say "# base rev: $BASE"
say "# freeze rev: $FREEZE"
say "# pure export (copied, never edited): $PURE_SRC"
say "# scratch (removed on exit): $S"
say "# live lane HEAD at run time: $(git -C "$LANE" rev-parse HEAD)"
say "# host: $(uname -srm)  python3: $(python3 -V 2>&1)  git: $(git --version)"
say "# load average at start: $(cat /proc/loadavg)"
say "# NOTE: the c2 selftest reads the LIVE lane (--lane default), so the live lane's bytes"
say "#       are part of the c2 before-value.  Live lane state at run time:"
say "#   knowledge entries: $(find "$LANE/corpus/knowledge" -maxdepth 1 -name '*.md' | wc -l)"
say "#   SOURCES.md sha256: $(sha256sum "$LANE/corpus/SOURCES.md" | cut -d' ' -f1)"
say "#   README.md F rows: $(grep -cE '^\| F[0-9]+ \|' "$LANE/corpus/README.md")"
say "#   live lane corpus dirty? $(git -C "$LANE" status --porcelain corpus/ | wc -l) changed path(s)"

# ---------------------------------------------------------------- (0) frozen instrument digests
say ""
say "## 0. the bytes this run used (frozen instruments + the before-value receipt)"
git -C "$LANE" archive "$FREEZE" corpus/instruments "$FIXTURE_REL" | tar -x -C "$S/tools"
cp -a "$PURE_SRC" "$S/pure"
say "sha256 of the frozen instruments this run used:"
( cd "$S/tools" && find . -type f \( -name 'r46-*.py' -o -name 'f29-fixture.py' \) -print0 | sort -z | xargs -0 sha256sum ) >>"$OUT"
say "sha256 of the committed before-value receipt (working tree):"
sha256sum "$RECEIPT" >>"$OUT"
say "sha256 of the committed before-value receipt (at the freeze rev):"
git -C "$LANE" show "$FREEZE:.ufo/waves/round-46/attempt2/controls/mutbat-before.txt" | sha256sum >>"$OUT"

GATE=$S/tools/corpus/instruments/r46-f29-gate.py
MUTBAT=$S/tools/corpus/instruments/r46-mutbat.py
FIXTURE=$S/tools/$FIXTURE_REL

# ---------------------------------------------------------------- (1) f29-gate replays
say ""
say "## 1. r46-f29-gate.py (frozen v1) replays"
git -C "$LANE" archive "$BASE" corpus | tar -x -C "$S/base"
git -C "$LANE" archive "$FREEZE" corpus | tar -x -C "$S/freeze"

say ""
say "### 1a. base export ($BASE)"
python3 "$GATE" --root "$S/base" --work "$S/work/gate-base" >>"$OUT" 2>&1
say "exit=$?"
base_sum=$(gate_summary "$S/base")
say "summary: $base_sum"
check "1a base export reads fixed=1/7" "1/7 H7" "$base_sum"

say ""
say "### 1b. freeze tree ($FREEZE)"
python3 "$GATE" --root "$S/freeze" --work "$S/work/gate-freeze" >>"$OUT" 2>&1
say "exit=$?"
freeze_sum=$(gate_summary "$S/freeze")
say "summary: $freeze_sum"
check "1b freeze tree reads fixed=2/7" "2/7 H4,H7" "$freeze_sum"

for mode in positive junk fabricated; do
  say ""
  say "### 1c. $mode fixture tree (built by the committed f29-fixture.py from the freeze tree)"
  rm -rf "$S/fx-$mode"
  python3 "$FIXTURE" --mode "$mode" --dir "$S/fx-$mode" --lane "$S/freeze" >>"$OUT" 2>&1
  say "fixture build exit=$?"
  python3 "$GATE" --root "$S/fx-$mode" --work "$S/work/gate-$mode" >>"$OUT" 2>&1
  say "exit=$?"
  fx_sum=$(gate_summary "$S/fx-$mode")
  fx_fixed=${fx_sum%%/*}
  say "summary: $fx_sum  (the red limbs are the complement of the green set)"
  if [ "$mode" = "positive" ]; then
    check "1c positive fixture tree reads 7/7 (the gate is not vacuously red)" "7" "$fx_fixed"
  elif [ "$fx_fixed" != "?" ] && [ "$fx_fixed" -lt 7 ]; then
    check "1c $mode fixture tree grades <7/7" "<7" "<7"
  else
    check "1c $mode fixture tree grades <7/7" "<7" "$fx_fixed"
  fi
done

say ""
say "### 1d. cross-check against the frozen R50 receipt (controls/f29-r50-receipt.txt)"
say "# the receipt states the junk tree at fixed=3/7 and the fabricated tree at fixed=3/7."
say "# The stale R50 scratch trees under /fast/scratch/hyaku/kasegi-r46/L1/f29r50/ carry a"
say "# SOURCES.md whose S074 row has 12 cells (not 11), so the census rejects them (E01) and"
say "# H3/H7 go red for that reason rather than for the defect the tree was built to carry."
say "# The trees rebuilt by the COMMITTED fixture script read 6/7: only H5 is red, which is the"
say "# limb the defect targets.  Re-derivation of the committed fixture is authoritative here."
R50=$LANE/.ufo/waves/round-46/attempt2/controls/f29-r50-receipt.txt
if [ -f "$R50" ]; then
  say "the frozen R50 receipt's own claims:"
  grep -nE 'junk tree|fabricated tree|Positive tree' "$R50" | sed 's/^/  /' >>"$OUT"
fi
for stale in /fast/scratch/hyaku/kasegi-r46/L1/f29r50/junk /fast/scratch/hyaku/kasegi-r46/L1/f29r50/fab; do
  if [ -d "$stale" ]; then
    say "stale R50 tree $stale re-graded with the frozen gate:"
    python3 "$GATE" --root "$stale" --work "$S/work/gate-stale-$$" 2>&1 | sed 's/^/  /' >>"$OUT"
  fi
done

# ---------------------------------------------------------------- (2) mutbat before-value replay
say ""
say "## 2. r46-mutbat.py (frozen v1) replay at the base export"
say "# the mutant lines and both summary lines must equal $RECEIPT"
say "# the two counters run concurrently (each has its own --work dir)"

python3 "$MUTBAT" --root "$S/base" --pure "$S/pure" --work "$S/work/mut-c1" --counter c1 --jobs 8 \
    >"$S/work/mut-c1.out" 2>&1 &
pid_c1=$!
python3 "$MUTBAT" --root "$S/base" --pure "$S/pure" --work "$S/work/mut-c2" --counter c2 --jobs 8 \
    >"$S/work/mut-c2.out" 2>&1 &
pid_c2=$!
wait $pid_c1; rc_c1=$?
wait $pid_c2; rc_c2=$?
say ""
say "### 2a. --counter c1"
sed -n '1,200p' "$S/work/mut-c1.out" >>"$OUT"
say "exit=$rc_c1"
say ""
say "### 2b. --counter c2"
sed -n '1,200p' "$S/work/mut-c2.out" >>"$OUT"
say "exit=$rc_c2"

python3 - "$S/work/mut-c1.out" "$S/work/mut-c2.out" "$RECEIPT" >>"$OUT" 2>&1 <<'PY'
import difflib
import re
import sys

mine_c1, mine_c2, receipt = sys.argv[1], sys.argv[2], sys.argv[3]
KEEP = re.compile(r"^(mutant=\S+ .*|mutbat counter=\S+ .*)$")


def lines(path):
    out = []
    for ln in open(path, encoding="utf-8"):
        ln = ln.rstrip("\n")
        if KEEP.match(ln):
            out.append(ln)
    return out


m1, m2, r = lines(mine_c1), lines(mine_c2), lines(receipt)
got = m1 + m2
print("before-value comparison")
print("  mine   (c1 run + c2 run): %d kept lines" % len(got))
print("  receipt (controls/mutbat-before.txt): %d kept lines" % len(r))
if got == r:
    print("  RESULT: IDENTICAL — every mutant line and both summary lines match the frozen receipt")
    sys.exit(0)
print("  RESULT: DIFFERENT")
for d in difflib.unified_diff(r, got, "receipt", "mine", lineterm="", n=1):
    print("  " + d)
sys.exit(1)
PY
cmp_rc=$?
say "comparison exit=$cmp_rc (0 = the replay reproduces the frozen before-value lines)"
check "2 mutbat replay reproduces the frozen before-value lines" "0" "$cmp_rc"
check "2a mutbat --counter c1 exit status (uncaught>0 => 1)" "1" "$rc_c1"
check "2b mutbat --counter c2 exit status (uncaught>0 => 1)" "1" "$rc_c2"

# ---------------------------------------------------------------- (3) stub-selftest control
say ""
say "## 3. stub-selftest control (the battery must grade the selftest, not markers)"
say "# the tree is copied to scratch, its c1 selftest is replaced by a stub whose cases all"
say "# pass (failures=0 unconditionally), and the battery is rerun: every mutant must read"
say "# verdict=uncaught and the battery must exit 1."
rm -rf "$S/stubtree"
mkdir -p "$S/stubtree"
git -C "$LANE" archive HEAD corpus | tar -x -C "$S/stubtree"
say "# the stubbed tree is a copy of the LIVE lane (git archive HEAD corpus); its counter is"
say "# byte-identical to the base export's counter, so the stub control grades the same bytes:"
say "  lane HEAD  r46-c1-gate.py sha256: $(sha256sum "$S/stubtree/corpus/instruments/r46-c1-gate.py" | cut -d' ' -f1)"
say "  base export r46-c1-gate.py sha256: $(sha256sum "$S/base/corpus/instruments/r46-c1-gate.py" | cut -d' ' -f1)"
say "  lane HEAD  r46-counters-selftest-c1.py sha256 (the file the stub replaces): $(sha256sum "$S/stubtree/corpus/instruments/r46-counters-selftest-c1.py" | cut -d' ' -f1)"
cat >"$S/stubtree/corpus/instruments/r46-counters-selftest-c1.py" <<'STUB'
#!/usr/bin/env python3
"""STUB selftest (control): every case passes; prints failures=0 unconditionally."""
import argparse
import sys

ap = argparse.ArgumentParser()
ap.add_argument("--lane")
ap.add_argument("--pure")
ap.add_argument("--counter")
ap.add_argument("--work")
ap.add_argument("--jobs", type=int, default=1)
ap.add_argument("--keep", action="store_true")
ap.parse_known_args()
print("case stub-control pass")
print("selftest cases=1 failures=0")
sys.exit(0)
STUB
say ""
say "\$ python3 $MUTBAT --root $S/stubtree --pure $S/pure --work $S/work/mut-stub --counter c1 --jobs 8"
python3 "$MUTBAT" --root "$S/stubtree" --pure "$S/pure" --work "$S/work/mut-stub" --counter c1 --jobs 8 \
    >"$S/work/mut-stub.out" 2>&1
stub_rc=$?
sed -n '1,200p' "$S/work/mut-stub.out" >>"$OUT"
say "exit=$stub_rc"
stub_uncaught=$(sed -n 's/^mutbat counter=c1 mutants=[0-9]* caught=[0-9]* equivalent=[0-9]* uncaught=\([0-9]*\).*/\1/p' "$S/work/mut-stub.out")
stub_caught=$(sed -n 's/^mutbat counter=c1 mutants=[0-9]* caught=\([0-9]*\) equivalent=[0-9]* uncaught=[0-9]*.*/\1/p' "$S/work/mut-stub.out")
stub_verdicts=$(grep -c 'verdict=uncaught' "$S/work/mut-stub.out")
say "summary: caught=$stub_caught uncaught=$stub_uncaught uncaught-verdict lines=$stub_verdicts battery exit=$stub_rc"
check "3 stub selftest: the battery exits 1" "1" "$stub_rc"
check "3 stub selftest: every mutant line reads verdict=uncaught" "20" "$stub_verdicts"
check "3 stub selftest: the summary reads uncaught=20 caught=0" "20 0" "$stub_uncaught $stub_caught"

# ---------------------------------------------------------------- (4) census validate (before the receipt closes)
say ""
say "## 4. sources-census.sh validate --root /home/vgpnk/Projects/shokunin kasegi"
bash "$CENSUS" validate --root /home/vgpnk/Projects/shokunin kasegi >>"$OUT" 2>&1
census_rc=$?
say "exit=$census_rc"
W04=$(bash "$CENSUS" validate --root /home/vgpnk/Projects/shokunin kasegi 2>/dev/null | grep -c '	W04	')
say "W04 warning lines: $W04"
check "4 census validate exits 0" "0" "$census_rc"
check "4 census validate prints three W04 warnings" "3" "$W04"

# ---------------------------------------------------------------- verdict
say ""
say "## verdict"
say "checks: $CHECKS   failed: $FAILED"
say "# receipt-end (a run that does not print this line was interrupted)"
if [ "$FAILED" -eq 0 ]; then
  sayq ""
  sayq "VERDICT: HOLDS — every declared before-value re-derived from committed bytes ($CHECKS checks, 0 failed)."
else
  sayq ""
  sayq "VERDICT: BROKEN — $FAILED of $CHECKS checks failed."
fi
exit $([ "$FAILED" -eq 0 ] && echo 0 || echo 1)
