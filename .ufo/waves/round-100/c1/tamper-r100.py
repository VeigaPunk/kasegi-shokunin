#!/usr/bin/env python3
"""kasegi round-100 C1 tamper harness — the census record's reconciliation.

Fifteen tamper classes over a census of record generated by the instrument at
a named revision. Twelve are the round-99 classes (format/digest/ancestry);
three are the round-100 reconciliation classes:

  T13 confined-edited        header `confined:` changed, header digest recomputed
  T14 body-numerator-host    body's resolve.py numerator set to the host-inclusive
                             value, body digest recomputed
  T15 class-table-internal   body class table INTERNAL set to the pinned numerator,
                             body digest recomputed

T13-T15 are the classes the round-99 check cannot see: it verifies the pinned
line, the host lines and the body against a regenerated body, but never
compares the header's confined count with the body's numerator, nor the class
table with the pinned numerator. T09 (poisoned cache) is a real cache test
here: its fake census carries all six header lines, so the check can only kill
it by measuring instead of reading the cache.

Usage:
  python3 -B .ufo/waves/round-100/c1/tamper-r100.py --lane . --rev <40-hex> \
      --alt-rev <40-hex> --instrument corpus/instruments/census-at-rev.py --work <scratch>
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

SEP = "\n---\n\n"
MEAS_RE = re.compile(r"^measured-at: ([0-9a-f]{40})$", re.M)
PINNED_RE = re.compile(r"^(pinned rate \(INTERNAL only; revision-stable\): )(.*)$", re.M)
HOST_RE = re.compile(r"^(host-inclusive rate[^:]*: )(.*)$", re.M)
OWNED_RE = re.compile(r"^(host-owned inputs: )(\d+)(.*)$", re.M)
CONF_RE = re.compile(r"^(confined: )(\d+)(.*)$", re.M)
HDR_PREFIXES = ("measured-at:", "home:", "pinned rate (INTERNAL only; revision-stable):",
                "host-inclusive rate", "host-owned inputs:", "confined:")
CASES = ("T01-pinned-edited", "T02-measured-at-repointed", "T03-measured-at-short",
         "T04-measured-at-missing", "T05-body-edited", "T06-host-line-removed",
         "T07-host-line-edited", "T08-body-from-other-rev", "T09-poisoned-cache",
         "T10-pinned-from-host", "T11-host-owned-edited", "T12-body-truncated",
         "T13-confined-edited", "T14-body-numerator-host", "T15-class-table-internal")


def run(cmd, env=None):
    return subprocess.run(cmd, capture_output=True, text=True, env=env)


def digest(s):
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def body_of(text):
    i = text.find(SEP)
    return text[i + len(SEP):] if i >= 0 else ""


def with_body(text, body):
    i = text.find(SEP)
    return text[:i + len(SEP)] + body


def header_of(text):
    """The six header lines in file order (before the separator)."""
    head = text[:text.find(SEP)]
    out = []
    for prefix in HDR_PREFIXES:
        m = re.search(r"^" + re.escape(prefix) + r".*$", head, re.M)
        if m:
            out.append(m.group(0))
    return out


def reseal(text, hdr=None, body=None):
    """Rewrite the record with the given header/body and recomputed digests."""
    head = text[:text.find(SEP)].split("\n")
    if hdr is not None:
        head = [ln for ln in head if not any(ln.startswith(p) for p in HDR_PREFIXES)]
        # keep the title/blank/description lines, then the header block, then digests
        keep = [ln for ln in head if not ln.startswith(("header-sha256:", "body-sha256:"))]
        while keep and keep[-1].strip() == "":
            keep.pop()
        lines = keep + hdr + ["header-sha256: " + digest("\n".join(hdr))]
    else:
        lines = list(head)
    b = body if body is not None else body_of(text)
    lines = [ln for ln in lines if not ln.startswith("body-sha256:")]
    lines.append("body-sha256: " + digest(b))
    return "\n".join(lines) + SEP + b


def bump(match, group, delta):
    return match.group(0)[:match.start(group)] + str(int(match.group(group)) + delta) + \
        match.group(0)[match.end(group):]


def tamper(case, text, alt_text, rev, alt_rev):
    if case == "T01-pinned-edited":
        m = PINNED_RE.search(text)
        mm = re.search(r"lane (\d+)/(\d+)", m.group(2))
        return PINNED_RE.sub(lambda _: m.group(1) + m.group(2)[:mm.start(2)] +
                             str(int(mm.group(2)) + 1) + m.group(2)[mm.end(2):], text, count=1)
    if case == "T02-measured-at-repointed":
        return MEAS_RE.sub("measured-at: " + alt_rev, text, count=1)
    if case == "T03-measured-at-short":
        return MEAS_RE.sub("measured-at: " + rev[:12], text, count=1)
    if case == "T04-measured-at-missing":
        return MEAS_RE.sub("", text, count=1)
    if case == "T05-body-edited":
        body = body_of(text)
        mm = re.search(r"^\| (GONE|INTERNAL) \| (\d+) \|$", body, re.M)
        return with_body(text, body[:mm.start(2)] + str(int(mm.group(2)) + 1) + body[mm.end(2):])
    if case == "T06-host-line-removed":
        return HOST_RE.sub("", text, count=1)
    if case == "T07-host-line-edited":
        m = HOST_RE.search(text)
        mm = re.search(r"lane (\d+)/(\d+)", m.group(2))
        return HOST_RE.sub(lambda _: m.group(1) + m.group(2)[:mm.start(2)] +
                           str(int(mm.group(2)) + 1) + m.group(2)[mm.end(2):], text, count=1)
    if case == "T08-body-from-other-rev":
        return with_body(text, body_of(alt_text))
    if case == "T09-poisoned-cache":
        hdr = header_of(text)
        pi = next(i for i, ln in enumerate(hdr) if ln.startswith("pinned rate"))
        mm = re.search(r"lane (\d+)/(\d+)", hdr[pi])
        fake = list(hdr)
        fake[pi] = hdr[pi][:mm.start(2)] + str(int(mm.group(2)) + 1) + hdr[pi][mm.end(2):]
        return {"cache": {"pinned": fake[pi], "header": fake, "body": body_of(text) + "\n"}}
    if case == "T10-pinned-from-host":
        pm, hm = PINNED_RE.search(text), HOST_RE.search(text)
        return PINNED_RE.sub(lambda _: pm.group(1) + hm.group(2), text, count=1)
    if case == "T11-host-owned-edited":
        return OWNED_RE.sub(lambda m: m.group(1) + str(int(m.group(2)) + 1) + m.group(3), text, count=1)
    if case == "T12-body-truncated":
        return with_body(text, body_of(text)[: len(body_of(text)) // 2])
    if case == "T13-confined-edited":
        hdr = [CONF_RE.sub(lambda m: m.group(1) + "0" + m.group(3), ln, count=1)
               if ln.startswith("confined:") else ln for ln in header_of(text)]
        return reseal(text, hdr=hdr)
    if case == "T14-body-numerator-host":
        body = body_of(text)
        hm = HOST_RE.search(text)
        mm = re.search(r"corpus (\d+)/(\d+)", hm.group(2))
        host_corpus = int(mm.group(1))
        bm = re.search(r"^- corpus alone: \*\*(\d+)/(\d+) = ([0-9.]+%)\*\*$", body, re.M)
        new = body[:bm.start(1)] + str(host_corpus) + body[bm.end(1):]
        return reseal(text, body=new)
    if case == "T15-class-table-internal":
        body = body_of(text)
        pm = PINNED_RE.search(text)
        mm = re.search(r"lane (\d+)/(\d+)", pm.group(2))
        pinned = int(mm.group(1))
        bm = re.search(r"^\| INTERNAL \| (\d+) \|$", body, re.M)
        new = body[:bm.start(1)] + str(pinned) + body[bm.end(1):]
        return reseal(text, body=new)
    return None


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--lane", required=True)
    ap.add_argument("--rev", required=True)
    ap.add_argument("--alt-rev", required=True)
    ap.add_argument("--instrument", required=True)
    ap.add_argument("--work", required=True)
    a = ap.parse_args(argv)
    lane = os.path.abspath(a.lane)
    work = os.path.abspath(a.work)
    os.makedirs(work, exist_ok=True)
    with open(a.instrument, "rb") as fh:
        inst_sha = hashlib.sha256(fh.read()).hexdigest()
    base = os.path.join(work, "census-" + a.rev[:12] + ".md")
    p = run([sys.executable, "-B", a.instrument, "--lane", lane, "--rev", a.rev,
             "--write", base, "--work", work])
    if p.returncode != 0:
        print("TAMPER error reason=write-failed rc=2 %s" % (p.stdout + p.stderr).strip())
        return 2
    alt = os.path.join(work, "census-" + a.alt_rev[:12] + ".md")
    p = run([sys.executable, "-B", a.instrument, "--lane", lane, "--rev", a.alt_rev,
             "--write", alt, "--work", work])
    if p.returncode != 0:
        alt = base
    text = open(base, encoding="utf-8").read()
    alt_text = open(alt, encoding="utf-8").read()
    killed = evaluated = 0
    for case in CASES:
        cw = os.path.join(work, "case-" + case)
        shutil.rmtree(cw, ignore_errors=True)
        os.makedirs(cw)
        t = tamper(case, text, alt_text, a.rev, a.alt_rev)
        cp = os.path.join(cw, "census.md")
        if isinstance(t, dict):
            fake = t["cache"]
            os.makedirs(os.path.join(cw, "cache"), exist_ok=True)
            mm = re.search(r"SKILL (\d+)/(\d+) = [\d.]+% \| corpus (\d+)/(\d+) = [\d.]+% "
                           r"\| lane (\d+)/(\d+) = [\d.]+%", fake["pinned"])
            sk, co, la = [int(mm.group(i)) for i in (1, 2)], [int(mm.group(i)) for i in (3, 4)], \
                         [int(mm.group(5)), int(mm.group(6))]
            payload = {"rates": {"rev": a.rev, "rows": 0, "host_owned": 0, "confined": 0,
                                 "skill": sk, "corpus": co, "lane": la,
                                 "skill_host": sk, "corpus_host": co, "lane_host": la,
                                 "skill_confined": 0, "corpus_confined": 0, "lane_confined": 0},
                       "body": fake["body"]}
            for key in (a.rev + ".json", a.rev + "-" + inst_sha[:12] + ".json"):
                with open(os.path.join(cw, "cache", key), "w", encoding="utf-8") as fh:
                    json.dump(payload, fh)
            hdr = fake["header"]
            t = "\n".join(["# citation-survival census — kasegi lane", "",
                           "Census of record — regenerated in round 100 at the revision below.", ""]
                          + hdr + ["header-sha256: " + digest("\n".join(hdr)),
                                   "body-sha256: " + digest(fake["body"])]) + SEP + fake["body"]
        with open(cp, "w", encoding="utf-8") as fh:
            fh.write(t)
        p = run([sys.executable, "-B", a.instrument, "--lane", lane, "--check", cp, "--work", cw])
        evaluated += 1
        ok = p.returncode != 0
        killed += ok
        reason = ""
        for line in (p.stdout + p.stderr).splitlines():
            if "CENSUS-CHECK" in line:
                reason = line.strip()
                break
        print("TAMPER %s rc=%d want=nonzero %s reason=%s" % (
            case, p.returncode, "PASS" if ok else "FAIL", reason))
    print("TAMPER-RESULT killed=%d total=%d evaluated=%d instrument_sha256=%s rc=%d" % (
        killed, len(CASES), evaluated, inst_sha, 0 if killed == len(CASES) else 1))
    return 0 if killed == len(CASES) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
